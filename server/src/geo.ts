type Point = [lat: number, lng: number];
const haversine = (p: Point, q: Point) => {
  const rad = Math.PI / 180;
  const h = Math.sin(((q[0] - p[0]) * rad) / 2) ** 2 + Math.cos(p[0] * rad) * Math.cos(q[0] * rad) * Math.sin(((q[1] - p[1]) * rad) / 2) ** 2;
  return Math.round(2 * 6371 * Math.asin(Math.sqrt(h)));
};

/** ระยะทางเส้นตรง (กม.) ระหว่างสองจังหวัด — null ถ้าไม่รู้จักจังหวัดใดจังหวัดหนึ่ง */
export function distanceKm(a: string | null | undefined, b: string | null | undefined): number | null {
  const p = a ? PROVINCES[a] : undefined, q = b ? PROVINCES[b] : undefined;
  return p && q ? haversine(p, q) : null;
}

export interface Place { lat?: number | null; lng?: number | null; province?: string | null }
/** พิกัดที่แม่นที่สุดเท่าที่มี: พิกัดจริง (lat/lng) ก่อน ถ้าไม่มีใช้พิกัดตัวจังหวัด */
const pointOf = (x: Place): Point | null =>
  x.lat != null && x.lng != null ? [Number(x.lat), Number(x.lng)] : (x.province && PROVINCES[x.province]) || null;

/** ระยะทางเส้นตรง (กม.) จากที่อยู่ของผู้ใช้ถึงมหาวิทยาลัย — null ถ้าไม่รู้ตำแหน่งฝั่งใดฝั่งหนึ่ง */
export function distanceBetween(home: Place, uni: Place): number | null {
  const p = pointOf(home), q = pointOf(uni);
  return p && q ? haversine(p, q) : null;
}

/** ระยะที่ถือว่า "ไกลสุด" — เกินนี้ได้ 0 คะแนน (ไทยเหนือจรดใต้ราว 1,600 กม.) */
export const FAR_KM = 1000;
/** คะแนนความใกล้บ้าน 0–100: จังหวัดเดียวกัน = 100 ลดลงเป็นเส้นตรงจนเหลือ 0 ที่ FAR_KM */
export const proximityScore = (km: number) => Math.round(100 * Math.max(0, 1 - km / FAR_KM));
