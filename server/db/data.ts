/** course = ชื่อหลักสูตร/ปริญญาตามไฟล์ ทปอ. (ถ้ามี) — ชื่อปริญญาบอกสายได้แน่นอนกว่าคำในชื่อสาขา เช่น นศ.บ. ภาพยนตร์และสื่อดิจิทัล = นิเทศศาสตร์ ไม่ใช่คอมพิวเตอร์ */
export function classify(faculty: string, program: string, course = ''): Field {
  const c = course.replace(/^หลักสูตร\s*/, '');
  if (/ครุศาสตรบัณฑิต|^ค\.บ\./.test(c)) return F.edu;
  if (/ศึกษาศาสตร์|ครุศาสตร์(?!อุตสาหกรรม)|วิทยาลัยการศึกษา|ฝึกหัดครู|พลศึกษา/.test(faculty) && !/จิตวิทยา|วิทยาศาสตร์การกีฬา|สาธารณสุข/.test(program)) return F.edu;
  if (/นิเทศศาสตรบัณฑิต|^นศ\.บ\./.test(c)) return F.mc;
  if (/บริหารธุรกิจบัณฑิต|บัญชีบัณฑิต|^บธ\.บ\.|^บช\.บ\./.test(c)) return F.bus;
  if (/เศรษฐศาสตรบัณฑิต|^ศ\.บ\./.test(c)) return F.eco;
  let hit = PROGRAM_RULES.find(([re]) => re.test(program))?.[1];
  // วท.บ. ที่ชื่อสาขามีคำว่า "การจัดการ/ผู้ประกอบการ" (เช่น การจัดการสิ่งแวดล้อม) ไม่ใช่สายบริหารธุรกิจ
  if (hit === F.bus && /วิทยาศาสตรบัณฑิต|^วท\.บ\./.test(c) && !/โลจิสติกส์|อสังหาริมทรัพย์/.test(program)) hit = PROGRAM_RULES.find(([re, f]) => f !== F.bus && re.test(program))?.[1];
  if (/ศิลปกรรมศาสตรบัณฑิต|^ศป\.บ\./.test(c) && (!hit || hit === F.bus || hit === F.com)) return F.art;
  return hit ?? FACULTY_RULES.find(([re]) => re.test(faculty))?.[1] ?? F.sci;
}
