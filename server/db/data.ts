/** ค่าเทอมของหลักสูตรจากตารางรายคณะ — null ถ้าไม่มีข้อมูล */
function ruleFee(uni: string, faculty: string, program: string, course: string): number | null {
  const rule = FACULTY_FEE[uni]?.find(([f]) => f === '*' || facKey(f) === facKey(faculty));
  if (!rule) return null;
  // คำที่ขึ้นต้นด้วย @ เทียบกับชื่อหลักสูตร/ปริญญาตามไฟล์ ทปอ. (เช่น "ครุศาสตรบัณฑิต สาขาวิชา...") คำอื่นเทียบกับชื่อสาขา; "ก+ข" = ต้องพบทั้งสองคำ
  const has = (kw: string) => (kw.startsWith('@') ? squash(course).includes(squash(kw.slice(1))) : squash(program).includes(squash(kw)));
  const hit = rule[2]?.find(([kw]) => kw.split('+').every(has));
  return hit ? hit[1] : rule[1];
}

